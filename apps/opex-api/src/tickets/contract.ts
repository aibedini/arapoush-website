import { z } from "zod";
import { PRIORITIES } from "@arapoush/schema";
import { Iso, IsoOrNull, Ok, route } from "../openapi/contract.ts";

export const STATUSES = ["new", "open", "pending", "on_hold", "resolved", "closed", "spam"] as const;
export const VIEWS = ["mine", "unassigned", "teams", "all", "overdue", "waiting", "closed", "spam"] as const;
const Status = z.enum(STATUSES).meta({ id: "TicketStatus" });
const Priority = z.enum(PRIORITIES).meta({ id: "TicketPriority" });

export const ListQuery = z.object({
  view: z.enum(VIEWS).default("all").describe("mine: assigned to you · unassigned · teams: your teams · all (open) · overdue: past SLA · waiting: on the customer · closed · spam"),
  q: z.string().max(200).optional().describe("#number, or text in the subject, requester name, email or company."),
  status: Status.optional().describe("Overrides `view`."),
  priority: Priority.optional(),
  team: z.string().max(40).optional().describe("Team id, or `none`."),
  assignee: z.string().max(40).optional().describe("Operator id, or `none`."),
  form: z.string().max(40).optional(),
  tag: z.string().max(40).optional(),
  before: z.string().optional().describe("Paging: last_activity_at of the last row you have."),
});
export const UpdateBody = z.strictObject({ status: Status.optional(), priority: Priority.optional(), team: z.string().max(40).nullable().optional().describe("Team id; null removes the team."), tags: z.array(z.string().min(1).max(40)).max(20).optional() });
export const ReferBody = z
  .strictObject({
    to: z.string().max(40).optional().describe("Operator id (or use `team`)."),
    team: z.string().max(40).optional(),
    message: z.string().trim().min(2).max(5000).describe("Internal; never sent to the customer."),
    transfer: z.boolean().default(false).describe("Also hand over ownership (assignee/team)."),
  })
  .refine((x) => !!x.to !== !!x.team, "Refer to one person or one team");
export const BulkBody = z.strictObject({ ids: z.array(z.string().max(40)).min(1).max(100), status: Status.optional(), priority: Priority.optional(), team: z.string().max(40).nullable().optional(), assignee: z.string().max(40).nullable().optional() });
export const SlaBody = z.partialRecord(Priority, z.strictObject({ first: z.number().int().min(5).max(60 * 24 * 30), resolve: z.number().int().min(5).max(60 * 24 * 90) })).describe("Minutes per priority: first response and resolution.");
export const SavedReplyBody = z.strictObject({ title: z.string().trim().min(1).max(120), team: z.string().max(40).nullable(), body: z.strictObject({ fa: z.string().max(10_000).optional(), en: z.string().max(10_000).optional(), tr: z.string().max(10_000).optional() }).describe("Per language; {name} and {number} are filled in.") });

const Sla = z.object({ next: IsoOrNull.describe("The nearest deadline"), kind: z.enum(["first", "resolve"]), breached: z.boolean(), firstResponseAt: IsoOrNull });
const Named = z.object({ id: z.string(), name: z.string().nullable() });
const ListItem = z
  .object({
    id: z.string(),
    number: z.number(),
    subject: z.string(),
    requester: z.object({ name: z.string().nullable(), email: z.string().nullable(), company: z.string().nullable() }),
    status: Status,
    priority: Priority,
    channel: z.enum(["form", "email"]),
    form: z.string().nullable(),
    team: Named.nullable(),
    assignee: Named.nullable(),
    tags: z.array(z.string()),
    unread: z.boolean().describe("Activity since you last opened it."),
    sla: Sla,
    last_activity_at: Iso,
    created_at: Iso,
  })
  .meta({ id: "TicketListItem" });
const L = z.object({ fa: z.string().optional(), en: z.string().optional(), tr: z.string().optional() });
const Event = z.object({ id: z.string(), kind: z.string().describe("submitted, reply_in, reply_out, note, referred, transferred, viewed, status, priority, team, tags, assigned, routed, merged, sla_breached"), actor: z.object({ kind: z.string(), id: z.string().nullable(), name: z.string().nullable() }), body: z.record(z.string(), z.unknown()).nullable(), meta: z.record(z.string(), z.unknown()), created_at: Iso });
const TicketView = z.object({
  ticket: z.object({
    id: z.string(),
    number: z.number(),
    status: Status,
    priority: Priority,
    channel: z.string(),
    tags: z.array(z.string()),
    locale: z.string().nullable(),
    page: z.string().nullable(),
    ip: z.string().nullable(),
    team: Named.nullable(),
    assignee: Named.nullable(),
    sla: Sla,
    created_at: Iso,
    resolved_at: IsoOrNull,
    merged_into: z.number().nullable(),
  }),
  data: z.object({ subject: z.string(), requester: z.object({ name: z.string().optional(), email: z.string().optional(), phone: z.string().optional(), company: z.string().optional() }), values: z.record(z.string(), z.unknown()), context: z.object({ spec: z.array(z.string()).optional() }).optional() }),
  form: z.object({ slug: z.string(), version: z.number().nullable(), fields: z.array(z.object({ id: z.string(), type: z.string(), label: L, options: z.array(z.object({ value: z.string(), label: L })).optional() })) }).nullable(),
  events: z.array(Event),
  reads: z.array(z.object({ principal_id: z.string(), display_name: z.string(), first_opened_at: Iso, last_read_at: Iso })).describe("Who opened it, first and last time."),
  attachments: z.array(z.object({ id: z.string(), event_id: z.string().nullable(), field: z.string().nullable(), name: z.string(), mime: z.string(), bytes: z.number(), scan: z.string(), created_at: Iso })),
  history: z.array(z.object({ number: z.number(), status: z.string(), created_at: Iso })).describe("Other tickets from the same requester."),
});
const Team = z.object({ id: z.string(), key: z.string(), name: z.string(), sla: z.record(z.string(), z.unknown()), auto_assign: z.boolean(), members: z.array(z.object({ id: z.string(), name: z.string(), role: z.enum(["agent", "lead"]), available: z.boolean() })), open: z.number() });

const Ref = z.object({ ref: z.string().max(40).describe("Ticket number (1042) or id (tkt_…)") });
const NoTicket = { status: 404, code: "NOT_FOUND", when: "No such ticket, or it is outside your teams (super admins see all)." };
const UnknownOperator = { status: 400, code: "UNKNOWN_OPERATOR", when: "Not an active operator." };
const UnknownTeam = { status: 400, code: "UNKNOWN_TEAM", when: "No such team." };
const S = "tickets/routes.ts";
const tags = ["Helpdesk"];
const agent = { audience: "manage" as const, auth: "session" as const, role: "operator" as const, source: S, tags };
const anyone = { ...agent, role: "viewer" as const };

