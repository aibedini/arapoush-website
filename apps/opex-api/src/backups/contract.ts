import { z } from "zod";
import { Iso, Ok, route } from "../openapi/contract.ts";

const S = "backups/routes.ts";
const tags = ["Backups"];

export const BackupKindSchema = z.enum(["full", "content", "database", "media"]).describe("full: database + media; content: pages, forms, media records and settings; database: every table; media: uploaded files only.");
export type BackupKind = z.infer<typeof BackupKindSchema>;
const Host = z.string().min(1).max(253).regex(/^[\w.-]+$/);
export const BackupConfig = z.strictObject({
  schedule: z.enum(["off", "daily", "weekly"]).default("off"),
  hour: z.number().int().min(0).max(23).default(3).describe("Server hour for scheduled backups."),
  kind: BackupKindSchema.default("full"),
  keep: z.number().int().min(1).max(365).default(14).describe("Archives kept on the server (oldest deleted first)."),
  remote: z
    .strictObject({
      type: z.enum(["none", "ftp", "ftps", "sftp", "s3", "webdav"]).default("none"),
      host: Host.nullable().default(null),
      port: z.number().int().min(1).max(65535).nullable().default(null),
      user: z.string().max(200).nullable().default(null),
      password: z.string().max(500).nullable().default(null).describe("Stored encrypted; shown as ••••••."),
      path: z.string().max(300).regex(/^[\w\-/. ]*$/).nullable().default("/opex-backups"),
      endpoint: z.string().url().regex(/^https:\/\//).nullable().default(null).describe("WebDAV base URL or S3 endpoint (https)."),
      bucket: z.string().max(100).regex(/^[\w.-]*$/).nullable().default(null),
      region: z.string().max(40).regex(/^[\w-]*$/).nullable().default(null),
      accessKey: z.string().max(200).nullable().default(null),
      secretKey: z.string().max(500).nullable().default(null).describe("Stored encrypted; shown as ••••••."),
    })
    .default({ type: "none", host: null, port: null, user: null, password: null, path: "/opex-backups", endpoint: null, bucket: null, region: null, accessKey: null, secretKey: null }),
});
export type BackupConfigT = z.infer<typeof BackupConfig>;

const Row = z.object({
  id: z.string(),
  kind: BackupKindSchema,
  trigger: z.enum(["manual", "schedule", "pre_restore"]),
  status: z.enum(["running", "done", "failed"]),
  bytes: z.number().nullable(),
  sha256: z.string().nullable(),
  encrypted: z.boolean(),
  remote: z.array(z.object({ at: Iso, to: z.string().nullable(), ok: z.boolean(), error: z.string().nullable() })),
  error: z.string().nullable(),
  started_by: z.string().nullable(),
  created_at: Iso,
  finished_at: Iso.nullable(),
});
const Id = z.object({ id: z.string().regex(/^bak_[0-9A-Z]{26}$/) });
export const RestoreBody = z.strictObject({
  id: z.string().regex(/^bak_[0-9A-Z]{26}$/).optional().describe("Restore a stored backup. Leave out to restore an uploaded file (?upload=1, octet-stream)."),
  scope: z.enum(["all", "content"]).default("all").describe("content: pages, forms and settings only; people, tickets and partners stay as they are."),
  media: z.boolean().default(true),
  confirm: z.literal("RESTORE").describe('Type "RESTORE": this replaces live data.'),
});

export const BACKUPS = {
  list: route({
    id: "listBackups",
    method: "GET",
    path: "/v1/manage/backups",
    audience: "manage",
    tags,
    summary: "Backups on the server, newest first",
    auth: "session",
    role: "operator",
    source: S,
    responses: { 200: { description: "Up to 200.", schema: z.array(Row) } },
  }),
  create: route({
    id: "createBackup",
    method: "POST",
    path: "/v1/manage/backups",
    audience: "manage",
    tags,
    summary: "Make a backup now (and send it to the remote, if one is set)",
    auth: "session",
    role: "super_admin",
    stepUp: true,
    source: S,
    body: z.strictObject({ kind: BackupKindSchema.default("full"), remote: z.boolean().default(true) }),
    responses: { 200: { description: "Done (the archive is encrypted).", schema: z.object({ id: z.string() }) } },
    errors: [{ status: 409, code: "BACKUP_RUNNING", when: "Another backup is still running." }],
    rateLimit: "6 per hour",
    audit: ["backup.create"],
  }),
  download: route({
    id: "downloadBackup",
    method: "GET",
    path: "/v1/manage/backups/:id/download",
    audience: "manage",
    tags,
    summary: "Download an archive (encrypted .opexbak)",
    auth: "session",
    role: "super_admin",
    stepUp: true,
    source: S,
    params: Id,
    responses: { 200: { description: "The encrypted archive.", contentType: "application/octet-stream" } },
    errors: [{ status: 404, code: "NOT_FOUND", when: "No such backup or file." }],
    audit: ["backup.download"],
  }),
  remove: route({
    id: "deleteBackup",
    method: "DELETE",
    path: "/v1/manage/backups/:id",
    audience: "manage",
    tags,
    summary: "Delete a stored archive",
    auth: "session",
    role: "super_admin",
    stepUp: true,
    source: S,
    params: Id,
    responses: { 200: { description: "Deleted.", schema: Ok } },
    errors: [{ status: 404, code: "NOT_FOUND", when: "No such backup." }],
    audit: ["backup.delete"],
  }),
  restore: route({
    id: "restoreBackup",
    method: "POST",
    path: "/v1/manage/backups/restore",
    audience: "manage",
    tags,
    summary: "Restore a backup (a safety backup is made first)",
    description: "Replaces the chosen data in one transaction. Sessions are signed out when people are restored. The audit log is never restored or rewritten.",
    auth: "session",
    role: "super_admin",
    stepUp: true,
    source: S,
    body: RestoreBody,
    responses: { 200: { description: "Restored.", schema: z.object({ safety: z.string(), tables: z.array(z.string()), mediaFiles: z.number(), from: z.string() }) } },
    errors: [
      { status: 400, code: "NOT_A_BACKUP", when: "The file is not an OPEX backup, the key is wrong or it is damaged." },
      { status: 400, code: "OTHER_TENANT", when: "The backup belongs to another tenant." },
      { status: 404, code: "NOT_FOUND", when: "No such backup." },
    ],
    rateLimit: "3 per hour",
    audit: ["backup.restore"],
  }),
  getConfig: route({
    id: "getBackupConfig",
    method: "GET",
    path: "/v1/manage/backups/config",
    audience: "manage",
    tags,
    summary: "Automatic backup and remote copy settings",
    auth: "session",
    role: "operator",
    source: S,
    responses: { 200: { description: "Secrets masked.", schema: BackupConfig } },
  }),
  putConfig: route({
    id: "putBackupConfig",
    method: "PUT",
    path: "/v1/manage/backups/config",
    audience: "manage",
    tags,
    summary: "Change automatic backup and remote copy settings",
    auth: "session",
    role: "super_admin",
    stepUp: true,
    source: S,
    body: BackupConfig,
    responses: { 200: { description: "Saved.", schema: Ok } },
    audit: ["backup.config"],
  }),
  testRemote: route({
    id: "testBackupRemote",
    method: "POST",
    path: "/v1/manage/backups/config/test",
    audience: "manage",
    tags,
    summary: "Send a small test file to the remote",
    auth: "session",
    role: "super_admin",
    stepUp: true,
    source: S,
    responses: { 200: { description: "Result.", schema: z.object({ ok: z.boolean(), to: z.string().nullable(), error: z.string().nullable() }) } },
    rateLimit: "10 per hour",
  }),
};
