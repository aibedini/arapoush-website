import { z } from "zod";
import { Iso, IsoOrNull, Ok, route } from "../openapi/contract.ts";

export const RoleSchema = z.string().regex(/^[a-z][a-z0-9_]{1,39}$/).describe("A built-in role (super_admin, operator, auditor, viewer) or the key of a custom role.").meta({ id: "OperatorRole" });
export const LoginBody = z.strictObject({ email: z.string().email().max(200), password: z.string().min(1).max(200) });
export const MfaBody = z.strictObject({ challenge: z.string().max(2000).describe("From the login answer (valid 5 minutes)."), code: z.string().regex(/^\d{6}$/) });
export const NewOperatorBody = z.strictObject({ email: z.string().email().max(200), display_name: z.string().min(2).max(120), role: RoleSchema, password: z.string().max(200).describe("Temporary; checked against the password policy.") });
export const OperatorPatch = z.strictObject({ role: RoleSchema.optional(), status: z.enum(["active", "disabled"]).optional(), display_name: z.string().min(2).max(120).optional(), reset_mfa: z.boolean().optional().describe("Forget the authenticator; the next sign-in enrols a new one."), unlock: z.boolean().optional() });

const S = "auth/routes.ts";
const tags = ["Sign-in and sessions"];
const Rate = "10 per minute per IP";
export const AUTH = {
  login: route({
    id: "login",
    method: "POST",
    path: "/v1/manage/auth/login",
    audience: "manage",
    tags,
    summary: "Step 1: email and password",
    description: "Answers with a short-lived challenge for step 2. Five wrong passwords lock the account (15, 30, 60 … minutes, max 24 h). The answer never says whether the email exists.",
    auth: "none",
    source: S,
    body: LoginBody,
    rateLimit: Rate,
    responses: { 200: { description: "Password accepted.", schema: z.object({ mfa: z.enum(["totp", "enroll"]).describe("totp: send a code to /auth/mfa; enroll: first sign-in, call /auth/mfa/enroll first."), challenge: z.string() }) } },
    errors: [{ status: 401, code: "UNAUTHENTICATED", when: "Wrong email or password, account locked or not active (same message for all)." }],
    audit: ["auth.password.ok", "auth.login.failure", "auth.lockout"],
  }),
  enroll: route({
    id: "mfaEnroll",
    method: "POST",
    path: "/v1/manage/auth/mfa/enroll",
    audience: "manage",
    tags,
    summary: "First sign-in: create the authenticator secret",
    auth: "none",
    source: S,
    body: z.strictObject({ challenge: z.string().max(2000) }),
    rateLimit: Rate,
    responses: { 200: { description: "Show `uri` as a QR code (or `secret` for manual entry), then confirm with /auth/mfa.", schema: z.object({ secret: z.string(), uri: z.string() }) } },
    errors: [
      { status: 401, code: "UNAUTHENTICATED", when: "Challenge expired; sign in again." },
      { status: 409, code: "MFA_ENROLLED", when: "An authenticator is already set up." },
    ],
    audit: ["auth.mfa.enroll_started"],
  }),
  mfa: route({
    id: "mfaVerify",
    method: "POST",
    path: "/v1/manage/auth/mfa",
    audience: "manage",
    tags,
    summary: "Step 2: authenticator code; starts the session",
    description: "Sets the `opex_session` cookie (HttpOnly, Secure in production, SameSite=Strict; ends after 15 minutes idle or 8 hours) and returns the CSRF token for writes. Each code works once.",
    auth: "none",
    source: S,
    body: MfaBody,
    rateLimit: Rate,
    responses: { 200: { description: "Signed in.", headers: { "Set-Cookie": "opex_session=…; HttpOnly; SameSite=Strict" }, schema: z.object({ csrf: z.string(), me: z.object({ id: z.string(), display: z.string(), role: RoleSchema }) }) } },
    errors: [{ status: 401, code: "UNAUTHENTICATED", when: "Wrong or reused code, or the challenge expired." }],
    audit: ["auth.login.success", "auth.mfa.enrolled", "auth.mfa.failure"],
  }),
  stepUp: route({
    id: "stepUp",
    method: "POST",
    path: "/v1/manage/auth/step-up",
    audience: "manage",
    tags,
    summary: "Confirm with the authenticator for sensitive actions (5 minutes)",
    auth: "session",
    role: "viewer",
    source: S,
    body: z.strictObject({ code: z.string().regex(/^\d{6}$/) }),
    rateLimit: Rate,
    responses: { 200: { description: "Confirmed.", schema: z.object({ ok: z.literal(true), validForSeconds: z.number() }) } },
    errors: [{ status: 401, code: "UNAUTHENTICATED", when: "The code is not valid." }],
    audit: ["auth.step_up", "auth.step_up.failure"],
  }),
  me: route({
    id: "me",
    method: "GET",
    path: "/v1/manage/auth/me",
    audience: "manage",
    tags,
    summary: "The signed-in operator",
    auth: "session",
    role: "viewer",
    source: S,
    responses: { 200: { description: "Who you are.", schema: z.object({ id: z.string(), display: z.string(), role: RoleSchema, stepUpValid: z.boolean(), permissions: z.array(z.string()).describe("Your effective permissions (role + your own additions − removals).") }) } },
  }),
  csrf: route({
    id: "csrfToken",
    method: "GET",
    path: "/v1/manage/auth/csrf",
    audience: "manage",
    tags,
    summary: "A CSRF token for this session (send as X-CSRF-Token on writes)",
    auth: "session",
    role: "viewer",
    source: S,
    responses: { 200: { description: "The token (rotated each call).", schema: z.object({ csrf: z.string() }) } },
  }),
  logout: route({ id: "logout", method: "POST", path: "/v1/manage/auth/logout", audience: "manage", tags, summary: "Sign out (revokes the session)", auth: "session", role: "viewer", source: S, responses: { 200: { description: "Signed out; cookie cleared.", schema: Ok } }, audit: ["auth.logout"] }),
  password: route({
    id: "changePassword",
    method: "POST",
    path: "/v1/manage/auth/password",
    audience: "manage",
    tags,
    summary: "Change your password",
    auth: "session",
    role: "viewer",
    stepUp: true,
    source: S,
    body: z.strictObject({ current: z.string().max(200), next: z.string().max(200) }),
    responses: { 200: { description: "Changed; your other sessions are signed out.", schema: Ok } },
    errors: [
      { status: 401, code: "UNAUTHENTICATED", when: "Current password is incorrect." },
      { status: 400, code: "WEAK_PASSWORD", when: "Shorter than 12 or longer than 128 characters, contains your email name, or (in production) appears in known breaches; `detail` says which." },
    ],
    audit: ["auth.password.changed"],
  }),
  sessions: route({
    id: "listSessions",
    method: "GET",
    path: "/v1/manage/sessions",
    audience: "manage",
    tags,
    summary: "Active sessions (yours; everyone's for super admins with ?all=1)",
    auth: "session",
    role: "viewer",
    source: S,
    query: z.object({ all: z.enum(["1"]).optional() }),
    responses: {
      200: {
        description: "Newest activity first (max 200).",
        schema: z.array(z.object({ id: z.string(), kind: z.string(), ip: z.string().nullable(), user_agent: z.string().nullable(), created_at: Iso, last_seen_at: Iso, expires_at: Iso, client_id: z.string().nullable(), display_name: z.string(), principal_kind: z.string() })),
      },
    },
  }),
  revokeSession: route({
    id: "revokeSession",
    method: "POST",
    path: "/v1/manage/sessions/:id/revoke",
    audience: "manage",
    tags,
    summary: "Sign a session out (yours; anyone's for super admins)",
    auth: "session",
    role: "viewer",
    source: S,
    params: z.object({ id: z.string().max(40) }),
    responses: { 200: { description: "Revoked (with its refresh tokens).", schema: Ok } },
    errors: [
      { status: 404, code: "NOT_FOUND", when: "No such session." },
      { status: 403, code: "FORBIDDEN", when: "Someone else's session and you are not a super admin." },
    ],
    audit: ["session.revoke"],
  }),
  operators: route({
    id: "listOperators",
    method: "GET",
    path: "/v1/manage/operators",
    audience: "manage",
    tags: ["Operators"],
    summary: "All console operators",
    auth: "session",
    role: "operator",
    source: S,
    responses: {
      200: {
        description: "Oldest first.",
        schema: z.array(z.object({ id: z.string(), email: z.string().nullable(), display_name: z.string(), role: RoleSchema, status: z.string(), last_login_at: IsoOrNull, locked_until: IsoOrNull, created_at: Iso, mfa: z.boolean(), perm_allow: z.array(z.string()), perm_deny: z.array(z.string()) })),
      },
    },
  }),
  createOperator: route({
    id: "createOperator",
    method: "POST",
    path: "/v1/manage/operators",
    audience: "manage",
    tags: ["Operators"],
    summary: "Invite an operator",
    auth: "session",
    role: "super_admin",
    stepUp: true,
    source: S,
    body: NewOperatorBody,
    responses: { 200: { description: "Created; they set up an authenticator at first sign-in.", schema: z.object({ id: z.string() }) } },
    errors: [
      { status: 400, code: "WEAK_PASSWORD", when: "The temporary password fails the policy." },
      { status: 409, code: "EMAIL_TAKEN", when: "An account with this email exists." },
      { status: 403, code: "ESCALATION", when: "You cannot give a role with permissions you do not have." },
      { status: 400, code: "UNKNOWN_ROLE", when: "No such role." },
    ],
    audit: ["operator.create"],
  }),
  updateOperator: route({
    id: "updateOperator",
    method: "PATCH",
    path: "/v1/manage/operators/:id",
    audience: "manage",
    tags: ["Operators"],
    summary: "Change role, status or name; reset MFA; unlock",
    auth: "session",
    role: "super_admin",
    stepUp: true,
    source: S,
    params: z.object({ id: z.string().max(40) }),
    body: OperatorPatch,
    responses: { 200: { description: "Updated. Disabling also signs their sessions out.", schema: Ok } },
    errors: [
      { status: 404, code: "NOT_FOUND", when: "No such operator." },
      { status: 403, code: "SELF_CHANGE", when: "You cannot change your own role or status." },
      { status: 403, code: "ESCALATION", when: "A role change needs users.permissions, and you cannot give a role with permissions you do not have." },
      { status: 409, code: "LAST_ADMIN", when: "The last active super admin cannot be demoted or disabled." },
      { status: 400, code: "UNKNOWN_ROLE", when: "No such role." },
    ],
    audit: ["operator.update"],
  }),
};
